"""Turns state/analytics.jsonl into state/research/performance.md — the feedback the editor reads before writing.

    python -m gr.analytics.digest

Takes the newest Insights row per Reel, joins it with the brief (hook line, on-screen hook, goal, angle, format,
style, presenter, voice) and ranks by a simple engagement score. Only numbers the API returned are shown.
"""
import json
from pathlib import Path

from gr.state import ROOT, STATE, load


def _rows():
    p = STATE / "analytics.jsonl"
    latest = {}
    if p.exists():
        for line in p.read_text(encoding="utf8").splitlines():
            try:
                r = json.loads(line)
            except ValueError:
                continue
            latest[r.get("id")] = r          # file is append-only, so the last row per id is the newest
    return [r for k, r in latest.items() if k]


def _brief(item):
    try:
        return json.loads((ROOT / item["brief"]).read_text(encoding="utf8"))
    except (KeyError, OSError, ValueError):
        return {}


def score(r):
    """Reach-weighted: views, plus shares/saves (strongest signals of a Reel worth more of), plus watch time."""
    views = r.get("views") or r.get("reach") or 0
    act = 3 * (r.get("shares") or 0) + 2 * (r.get("saved") or 0) + (r.get("comments") or 0)
    watch = (r.get("ig_reels_avg_watch_time") or 0) / 1000
    return views + 25 * act + 40 * watch


def describe(r, it, ep):
    v = ep.get("viral") or {}
    beats = ep.get("beats") or []
    hook = next((b for b in beats if b.get("type") == "hook"), {})
    vo = hook.get("vo") or ep.get("intro", "")
    m = ", ".join(f"{k}={r[k]}" for k in ("views", "reach", "shares", "saved", "comments", "likes") if r.get(k) is not None)
    if r.get("ig_reels_avg_watch_time") is not None:
        m += f", avg_watch={r['ig_reels_avg_watch_time'] / 1000:.1f}s"
    tags = " · ".join(str(x) for x in (it.get("format"), it.get("series"), it.get("style"), ep.get("presenter"),
                                           v.get("goal"), v.get("angle")) if x)
    return f"- **{it.get('title', r['id'])}** ({r['id']}; {tags})\n  - hook VO: \"{vo}\"\n  - on-screen: \"{hook.get('text', '')}\"\n  - {m}"


def build():
    items = load("queue.json", {"items": {}})["items"]
    rows = sorted(_rows(), key=score, reverse=True)
    out = ["# What is working (auto-generated by gr/analytics/digest.py — do not edit)", ""]
    if not rows:
        out += ["No Instagram Insights yet (the maintenance job pulls them nightly once Reels are published).",
                "Until data exists, follow the going-viral defaults in docs/prompts/editor.md and vary hook angles so",
                "the next digest has something to compare."]
    else:
        joined = [(r, items.get(r["id"], {}), _brief(items.get(r["id"], {}))) for r in rows]
        out += [f"{len(rows)} Reel(s) with Insights. Score = views + 25·(3·shares + 2·saves + comments) + 40·avg-watch-seconds.", "",
                "## Winners — copy their hook angle, goal, pacing and format (never their exact words)"]
        out += [describe(*j) for j in joined[:5]]
        if len(joined) > 5:
            out += ["", "## Losers — avoid these hook angles / formats unless the angle changes"]
            out += [describe(*j) for j in joined[-3:]]
        groups = {}
        for r, it, ep in joined:
            for key in ("format", "style"):
                if it.get(key):
                    groups.setdefault(f"{key}={it[key]}", []).append(score(r))
            g = (ep.get("viral") or {}).get("goal")
            if g:
                groups.setdefault(f"goal={g}", []).append(score(r))
        if groups:
            out += ["", "## Average score by attribute (n ≥ 2 only)"]
            for k, v in sorted(groups.items(), key=lambda kv: -sum(kv[1]) / len(kv[1])):
                if len(v) >= 2:
                    out.append(f"- {k}: {sum(v) / len(v):.0f} (n={len(v)})")
    p = STATE / "research" / "performance.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(out) + "\n", encoding="utf8")
    return p


if __name__ == "__main__":
    print(build().relative_to(ROOT).as_posix())
